import React from 'react';
import { useTranslation } from 'react-i18next';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { Badge } from '@/components/ui/badge';
import { 
  FileText, ShieldCheck, Lock, Save, AlertCircle, CheckCircle2 
} from 'lucide-react';
import { cn } from '@/lib/utils';
import type { MaterialityJustification } from '@shared/types';
import { isJustificationComplete } from '../services/materiality-justification';

export interface MaterialityJustificationPanelProps {
  justification?: MaterialityJustification;
  isLocked: boolean; // Locks numerical calculations
  isJustificationLocked?: boolean; // Narrative locking (only when final approved / deletion)
  onSaveJustification: (justification: MaterialityJustification) => void;
  isSaving?: boolean;
}

export function MaterialityJustificationPanel({
  justification,
  isLocked,
  isJustificationLocked = false,
  onSaveJustification,
  isSaving = false,
}: MaterialityJustificationPanelProps) {
  const { t } = useTranslation('scoping');

  const initialText =
    justification?.justificationText ||
    justification?.supplementaryNotes ||
    justification?.autoGeneratedNarrative ||
    '';

  const [notes, setNotes] = React.useState(initialText);
  const [isDirty, setIsDirty] = React.useState(false);

  React.useEffect(() => {
    const current =
      justification?.justificationText ||
      justification?.supplementaryNotes ||
      justification?.autoGeneratedNarrative ||
      '';
    setNotes(current);
    setIsDirty(false);
  }, [justification]);

  const isComplete = React.useMemo(() => {
    return isJustificationComplete(justification);
  }, [justification]);

  const handleSave = () => {
    const trimmed = notes.trim();
    const updated: MaterialityJustification = {
      ...(justification || {}),
      justificationText: trimmed,
      supplementaryNotes: trimmed,
      autoGeneratedNarrative: trimmed,
      justifiedAt: new Date().toISOString(),
    };
    onSaveJustification(updated);
    setIsDirty(false);
  };

  const isEditable = !isJustificationLocked;

  return (
    <Card className="border-border/40 shadow-xs bg-card text-card-foreground">
      <CardHeader className="p-4 sm:p-5 border-b border-border/20 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex flex-col min-w-0">
          <div className="flex items-center gap-2">
            <CardTitle className="font-display text-sm sm:text-base font-bold text-primary tracking-tight flex items-center gap-1.5">
              <FileText className="h-4 w-4 text-secondary shrink-0" aria-hidden="true" />
              <span>{t('justificationPanel.title')}</span>
            </CardTitle>
            <Badge
              variant="outline"
              className={cn(
                "text-xs font-semibold px-2 py-0.5 rounded border leading-tight shrink-0",
                isComplete
                  ? "bg-emerald-50 text-emerald-700 border-emerald-300 dark:bg-emerald-950 dark:text-emerald-300"
                  : "bg-amber-50 text-amber-700 border-amber-300 dark:bg-amber-950 dark:text-amber-300"
              )}
            >
              {isComplete ? (
                <span className="flex items-center gap-1">
                  <CheckCircle2 className="h-3 w-3 text-emerald-600" aria-hidden="true" />
                  {t('scoping:justification.statusComplete')}
                </span>
              ) : (
                <span className="flex items-center gap-1">
                  <AlertCircle className="h-3 w-3 text-amber-600" aria-hidden="true" />
                  {t('scoping:justification.statusPending')}
                </span>
              )}
            </Badge>
          </div>
          <CardDescription className="text-xs text-muted-foreground mt-0.5">
            {t('justificationPanel.subtitle')}
          </CardDescription>
        </div>

        <div className="flex items-center gap-2 shrink-0">
          {isLocked && !isJustificationLocked && (
            <Badge variant="outline" className="bg-primary/5 text-primary border-primary/20 text-xs font-semibold">
              <Lock className="h-3 w-3 mr-1 text-primary" aria-hidden="true" />
              {t('justificationPanel.calcLockedNote')}
            </Badge>
          )}

          {isEditable && (
            <Button
              type="button"
              size="sm"
              onClick={handleSave}
              disabled={!isDirty || isSaving}
              className="h-8 gap-1.5 text-xs font-bold rounded-lg bg-secondary text-on-secondary hover:bg-secondary/90 transition shadow-sm"
            >
              <Save className="h-3.5 w-3.5" aria-hidden="true" />
              <span>{isSaving ? t('common:actions.saving', { defaultValue: 'Menyimpan...' }) : t('justificationPanel.btnSaveJustification')}</span>
            </Button>
          )}
        </div>
      </CardHeader>

      <CardContent className="p-4 sm:p-5 flex flex-col gap-3">
        <div className="flex flex-col gap-1.5">
          <label htmlFor="materiality-justification-notes" className="text-xs font-bold text-foreground uppercase tracking-wider">
            {t('justificationPanel.notesLabel')}
          </label>
          <Textarea
            id="materiality-justification-notes"
            value={notes}
            onChange={(e) => {
              setNotes(e.target.value);
              setIsDirty(true);
            }}
            disabled={!isEditable}
            rows={3}
            placeholder={t('justificationPanel.notesPlaceholder')}
            className="text-xs resize-y bg-surface-container-low border-border/40 focus:bg-background rounded-lg min-h-[80px]"
          />
          <div className="flex items-center justify-between text-xs text-muted-foreground mt-0.5">
            <span className="text-muted-foreground font-normal">{t('justificationPanel.antiDeadlockHint')}</span>
            <span className="font-mono">{notes.length} {t('justificationPanel.characters')}</span>
          </div>
        </div>
      </CardContent>
    </Card>
  );
}
