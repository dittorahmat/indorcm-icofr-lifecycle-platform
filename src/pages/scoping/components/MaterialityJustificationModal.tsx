import React from 'react';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogFooter
} from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { Label } from '@/components/ui/label';
import { Badge } from '@/components/ui/badge';
import { ShieldCheck, FileText, CheckCircle2, AlertCircle } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import { toast } from 'sonner';
import { cn } from '@/lib/utils';
import type {
  MaterialitySimulation,
  MaterialityJustification
} from '@shared/types';

interface MaterialityJustificationModalProps {
  isOpen: boolean;
  onOpenChange: (open: boolean) => void;
  simulation: MaterialitySimulation;
  onSave: (justification: MaterialityJustification) => void;
  isLocked?: boolean;
}

export function MaterialityJustificationModal({
  isOpen,
  onOpenChange,
  simulation,
  onSave,
  isLocked = false
}: MaterialityJustificationModalProps) {
  const { t } = useTranslation(['scoping', 'common']);

  const initialText =
    simulation.materialityJustification?.justificationText ||
    simulation.materialityJustification?.supplementaryNotes ||
    simulation.materialityJustification?.autoGeneratedNarrative ||
    '';

  const [justificationText, setJustificationText] = React.useState<string>(initialText);

  React.useEffect(() => {
    if (isOpen) {
      const currentText =
        simulation.materialityJustification?.justificationText ||
        simulation.materialityJustification?.supplementaryNotes ||
        simulation.materialityJustification?.autoGeneratedNarrative ||
        '';
      setJustificationText(currentText);
    }
  }, [isOpen, simulation.materialityJustification]);

  const trimmedText = justificationText.trim();
  const isComplete = trimmedText.length > 0;

  const handleSave = () => {
    if (!isComplete) {
      toast.error(t('scoping:justification.incompleteAlertTitle'), {
        description: t('scoping:justification.incompleteAlertDesc')
      });
      return;
    }

    const payload: MaterialityJustification = {
      ...(simulation.materialityJustification || {}),
      justificationText: trimmedText,
      supplementaryNotes: trimmedText,
      autoGeneratedNarrative: trimmedText,
      justifiedAt: new Date().toISOString()
    };

    onSave(payload);
    toast.success(t('scoping:justification.savedSuccess'));
    onOpenChange(false);
  };

  const omValue = simulation.omPercentage ?? 5;
  const haircutValue = simulation.haircutPercentage ?? 25;
  const pmPct = 100 - haircutValue;

  return (
    <Dialog open={isOpen} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-2xl w-[calc(100vw-2rem)] max-h-[90dvh] overflow-y-auto border border-border bg-card p-4 sm:p-6 shadow-xl rounded-lg">
        <DialogHeader className="border-b border-border pb-4">
          <div className="flex flex-col sm:flex-row sm:justify-between sm:items-center flex-wrap gap-2 min-w-0">
            <div className="flex items-center gap-2">
              <ShieldCheck className="h-5 w-5 text-primary" />
              <DialogTitle className="text-base font-semibold text-foreground">
                {t('scoping:justification.modalTitle')}
              </DialogTitle>
            </div>
            <Badge
              variant="outline"
              className={cn(
                "font-medium text-xs rounded-md px-2.5 py-0.5",
                isComplete
                  ? "bg-emerald-50 text-emerald-700 border-emerald-300"
                  : "bg-amber-50 text-amber-700 border-amber-300"
              )}
            >
              {isComplete ? (
                <span className="flex items-center gap-1.5">
                  <CheckCircle2 className="h-3.5 w-3.5 text-emerald-600" />
                  {t('scoping:justification.statusComplete')}
                </span>
              ) : (
                <span className="flex items-center gap-1.5">
                  <AlertCircle className="h-3.5 w-3.5 text-amber-600" />
                  {t('scoping:justification.statusPending')}
                </span>
              )}
            </Badge>
          </div>
          <DialogDescription className="text-xs text-muted-foreground pt-1 leading-normal">
            {t('scoping:justification.modalDescription')}
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-4 py-4">
          {/* Summary parameter info */}
          <div className="rounded-md border border-border bg-muted/20 p-3 text-xs text-muted-foreground flex flex-wrap items-center gap-x-4 gap-y-1">
            <span>
              <strong className="text-foreground">{t('scoping:form.benchmark')}:</strong> {simulation.basis || '-'}
            </span>
            <span>
              <strong className="text-foreground">OM:</strong> {omValue}%
            </span>
            <span>
              <strong className="text-foreground">Haircut:</strong> {haircutValue}% (PM {pmPct}%)
            </span>
          </div>

          <div className="space-y-2">
            <div className="flex items-center justify-between gap-2">
              <Label htmlFor="justification-text" className="text-xs font-semibold text-foreground">
                {t('scoping:justification.notesLabel')}
              </Label>
              <span className="text-xs text-muted-foreground font-mono">
                {t('scoping:justification.charCount', { count: trimmedText.length })}
              </span>
            </div>
            <p className="text-xs text-muted-foreground">
              {t('scoping:justification.notesDesc')}
            </p>
            <Textarea
              id="justification-text"
              value={justificationText}
              onChange={(e) => !isLocked && setJustificationText(e.target.value)}
              disabled={isLocked}
              rows={5}
              placeholder={t('scoping:justification.notesPlaceholder')}
              className="min-h-[120px] text-base sm:text-sm rounded-md border-border bg-background focus:ring-primary"
            />
          </div>
        </div>

        <DialogFooter className="border-t border-border pt-4 flex flex-col-reverse sm:flex-row sm:items-center sm:justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={() => onOpenChange(false)}
            className="text-xs rounded-md w-full sm:w-auto min-h-[44px]"
          >
            {t('common:actions.cancel')}
          </Button>
          {!isLocked && (
            <Button
              type="button"
              size="sm"
              onClick={handleSave}
              className="text-xs rounded-md font-semibold w-full sm:w-auto min-h-[44px]"
            >
              <FileText className="h-3.5 w-3.5 mr-1.5" />
              {t('scoping:justification.saveButton')}
            </Button>
          )}
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
