import React from 'react';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogFooter
} from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { Label } from '@/components/ui/label';
import { Badge } from '@/components/ui/badge';
import { RadioGroup, RadioGroupItem } from '@/components/ui/radio-group';
import { ShieldCheck, FileText, CheckCircle2, AlertCircle, Sparkles } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import { toast } from 'sonner';
import { cn } from '@/lib/utils';
import {
  generateMaterialityNarrative,
  isJustificationComplete
} from '@/pages/scoping/services/materiality-justification';
import type {
  MaterialitySimulation,
  MaterialityJustification,
  EntityCharacteristics,
  InternalControlMaturity,
  AuditAdjustmentHistory,
  SystemStability
} from '@shared/types';

interface MaterialityJustificationModalProps {
  isOpen: boolean;
  onOpenChange: (open: boolean) => void;
  simulation: MaterialitySimulation;
  onSave: (justification: MaterialityJustification) => void;
  isLocked?: boolean;
}

export function MaterialityJustificationModal({
  isOpen,
  onOpenChange,
  simulation,
  onSave,
  isLocked = false
}: MaterialityJustificationModalProps) {
  const { t, i18n } = useTranslation(['scoping', 'common']);
  const currentLang = (i18n.language?.startsWith('en') ? 'en' : 'id') as 'id' | 'en';

  const initialJustification = simulation.materialityJustification;

  const [entityCharacteristics, setEntityCharacteristics] = React.useState<EntityCharacteristics | undefined>(
    initialJustification?.entityCharacteristics
  );
  const [internalControlMaturity, setInternalControlMaturity] = React.useState<InternalControlMaturity | undefined>(
    initialJustification?.internalControlMaturity
  );
  const [auditAdjustmentHistory, setAuditAdjustmentHistory] = React.useState<AuditAdjustmentHistory | undefined>(
    initialJustification?.auditAdjustmentHistory
  );
  const [systemStability, setSystemStability] = React.useState<SystemStability | undefined>(
    initialJustification?.systemStability
  );
  const [supplementaryNotes, setSupplementaryNotes] = React.useState<string>(
    initialJustification?.supplementaryNotes || ''
  );

  React.useEffect(() => {
    if (isOpen) {
      setEntityCharacteristics(simulation.materialityJustification?.entityCharacteristics);
      setInternalControlMaturity(simulation.materialityJustification?.internalControlMaturity);
      setAuditAdjustmentHistory(simulation.materialityJustification?.auditAdjustmentHistory);
      setSystemStability(simulation.materialityJustification?.systemStability);
      setSupplementaryNotes(simulation.materialityJustification?.supplementaryNotes || '');
    }
  }, [isOpen, simulation.materialityJustification]);

  const liveNarrative = React.useMemo(() => {
    return generateMaterialityNarrative({
      basis: simulation.basis || t('scoping:form.benchmark'),
      omPercentage: simulation.omPercentage ?? 5,
      haircutPercentage: simulation.haircutPercentage ?? 25,
      entityCharacteristics,
      internalControlMaturity,
      auditAdjustmentHistory,
      systemStability,
      language: currentLang
    });
  }, [
    simulation.basis,
    simulation.omPercentage,
    simulation.haircutPercentage,
    entityCharacteristics,
    internalControlMaturity,
    auditAdjustmentHistory,
    systemStability,
    currentLang,
    t
  ]);

  const isComplete = Boolean(
    entityCharacteristics &&
    internalControlMaturity &&
    auditAdjustmentHistory &&
    systemStability
  );

  const handleSave = () => {
    if (!isComplete) {
      toast.error(t('scoping:justification.incompleteAlertTitle'), {
        description: t('scoping:justification.incompleteAlertDesc')
      });
      return;
    }

    const payload: MaterialityJustification = {
      entityCharacteristics: entityCharacteristics!,
      internalControlMaturity: internalControlMaturity!,
      auditAdjustmentHistory: auditAdjustmentHistory!,
      systemStability: systemStability!,
      autoGeneratedNarrative: liveNarrative,
      supplementaryNotes: supplementaryNotes.trim() || undefined,
      justifiedAt: new Date().toISOString()
    };

    onSave(payload);
    toast.success(t('scoping:justification.savedSuccess'));
    onOpenChange(false);
  };

  return (
    <Dialog open={isOpen} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-3xl max-h-[90vh] overflow-y-auto border border-border bg-card p-6 shadow-xl rounded-lg">
        <DialogHeader className="border-b border-border pb-4">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <ShieldCheck className="h-5 w-5 text-primary" />
              <DialogTitle className="text-base font-semibold text-foreground">
                {t('scoping:justification.modalTitle')}
              </DialogTitle>
            </div>
            <Badge
              variant="outline"
              className={cn(
                "font-medium text-xs rounded-md px-2.5 py-0.5",
                isComplete
                  ? "bg-emerald-50 text-emerald-700 border-emerald-300"
                  : "bg-amber-50 text-amber-700 border-amber-300"
              )}
            >
              {isComplete ? (
                <span className="flex items-center gap-1.5">
                  <CheckCircle2 className="h-3.5 w-3.5 text-emerald-600" />
                  {t('scoping:justification.statusComplete')}
                </span>
              ) : (
                <span className="flex items-center gap-1.5">
                  <AlertCircle className="h-3.5 w-3.5 text-amber-600" />
                  {t('scoping:justification.statusPending')}
                </span>
              )}
            </Badge>
          </div>
          <DialogDescription className="text-xs text-muted-foreground pt-1 leading-normal">
            {t('scoping:justification.modalDescription')}
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-6 py-4">
          {/* Factor 1: Entity Characteristics */}
          <div className="rounded-md border border-border p-4 bg-background space-y-3">
            <div>
              <Label className="text-xs font-semibold text-foreground">
                {t('scoping:justification.factor1Title')}
              </Label>
              <p className="text-xs text-muted-foreground mt-0.5">
                {t('scoping:justification.factor1Desc')}
              </p>
            </div>
            <RadioGroup
              value={entityCharacteristics}
              onValueChange={(val) => !isLocked && setEntityCharacteristics(val as EntityCharacteristics)}
              disabled={isLocked}
              className="grid grid-cols-1 sm:grid-cols-2 gap-2"
            >
              {[
                { id: 'profit_oriented', label: t('scoping:justification.options.profit_oriented') },
                { id: 'asset_intensive', label: t('scoping:justification.options.asset_intensive') },
                { id: 'revenue_driven', label: t('scoping:justification.options.revenue_driven') },
                { id: 'volatile_breakeven', label: t('scoping:justification.options.volatile_breakeven') }
              ].map((opt) => (
                <label
                  key={opt.id}
                  className={cn(
                    "flex items-start space-x-2 rounded-md border p-3 cursor-pointer text-xs transition-colors",
                    entityCharacteristics === opt.id
                      ? "border-primary bg-primary/5 font-medium text-foreground"
                      : "border-border hover:bg-muted/50 text-muted-foreground"
                  )}
                >
                  <RadioGroupItem value={opt.id} id={`ec-${opt.id}`} className="mt-0.5" />
                  <span className="leading-snug">{opt.label}</span>
                </label>
              ))}
            </RadioGroup>
          </div>

          {/* Factor 2: Internal Control Maturity */}
          <div className="rounded-md border border-border p-4 bg-background space-y-3">
            <div>
              <Label className="text-xs font-semibold text-foreground">
                {t('scoping:justification.factor2Title')}
              </Label>
              <p className="text-xs text-muted-foreground mt-0.5">
                {t('scoping:justification.factor2Desc')}
              </p>
            </div>
            <RadioGroup
              value={internalControlMaturity}
              onValueChange={(val) => !isLocked && setInternalControlMaturity(val as InternalControlMaturity)}
              disabled={isLocked}
              className="grid grid-cols-1 sm:grid-cols-3 gap-2"
            >
              {[
                { id: 'effective_strong', label: t('scoping:justification.options.effective_strong') },
                { id: 'moderate', label: t('scoping:justification.options.moderate_control') },
                { id: 'deficient_material_weakness', label: t('scoping:justification.options.deficient_material_weakness') }
              ].map((opt) => (
                <label
                  key={opt.id}
                  className={cn(
                    "flex items-start space-x-2 rounded-md border p-3 cursor-pointer text-xs transition-colors",
                    internalControlMaturity === opt.id
                      ? "border-primary bg-primary/5 font-medium text-foreground"
                      : "border-border hover:bg-muted/50 text-muted-foreground"
                  )}
                >
                  <RadioGroupItem value={opt.id} id={`icm-${opt.id}`} className="mt-0.5" />
                  <span className="leading-snug">{opt.label}</span>
                </label>
              ))}
            </RadioGroup>
          </div>

          {/* Factor 3: Audit Adjustment History */}
          <div className="rounded-md border border-border p-4 bg-background space-y-3">
            <div>
              <Label className="text-xs font-semibold text-foreground">
                {t('scoping:justification.factor3Title')}
              </Label>
              <p className="text-xs text-muted-foreground mt-0.5">
                {t('scoping:justification.factor3Desc')}
              </p>
            </div>
            <RadioGroup
              value={auditAdjustmentHistory}
              onValueChange={(val) => !isLocked && setAuditAdjustmentHistory(val as AuditAdjustmentHistory)}
              disabled={isLocked}
              className="grid grid-cols-1 sm:grid-cols-3 gap-2"
            >
              {[
                { id: 'low_clean', label: t('scoping:justification.options.low_clean') },
                { id: 'moderate', label: t('scoping:justification.options.moderate_adjustment') },
                { id: 'significant', label: t('scoping:justification.options.significant_adjustment') }
              ].map((opt) => (
                <label
                  key={opt.id}
                  className={cn(
                    "flex items-start space-x-2 rounded-md border p-3 cursor-pointer text-xs transition-colors",
                    auditAdjustmentHistory === opt.id
                      ? "border-primary bg-primary/5 font-medium text-foreground"
                      : "border-border hover:bg-muted/50 text-muted-foreground"
                  )}
                >
                  <RadioGroupItem value={opt.id} id={`aah-${opt.id}`} className="mt-0.5" />
                  <span className="leading-snug">{opt.label}</span>
                </label>
              ))}
            </RadioGroup>
          </div>

          {/* Factor 4: Business & IT Systems Stability */}
          <div className="rounded-md border border-border p-4 bg-background space-y-3">
            <div>
              <Label className="text-xs font-semibold text-foreground">
                {t('scoping:justification.factor4Title')}
              </Label>
              <p className="text-xs text-muted-foreground mt-0.5">
                {t('scoping:justification.factor4Desc')}
              </p>
            </div>
            <RadioGroup
              value={systemStability}
              onValueChange={(val) => !isLocked && setSystemStability(val as SystemStability)}
              disabled={isLocked}
              className="grid grid-cols-1 sm:grid-cols-2 gap-2"
            >
              {[
                { id: 'stable', label: t('scoping:justification.options.stable_system') },
                { id: 'major_change_erp_restructure', label: t('scoping:justification.options.major_change_erp_restructure') }
              ].map((opt) => (
                <label
                  key={opt.id}
                  className={cn(
                    "flex items-start space-x-2 rounded-md border p-3 cursor-pointer text-xs transition-colors",
                    systemStability === opt.id
                      ? "border-primary bg-primary/5 font-medium text-foreground"
                      : "border-border hover:bg-muted/50 text-muted-foreground"
                  )}
                >
                  <RadioGroupItem value={opt.id} id={`ss-${opt.id}`} className="mt-0.5" />
                  <span className="leading-snug">{opt.label}</span>
                </label>
              ))}
            </RadioGroup>
          </div>

          {/* Auto-generated narrative card */}
          <div className="rounded-md border border-primary/20 bg-primary/[0.03] p-4 space-y-2">
            <div className="flex items-center gap-1.5">
              <Sparkles className="h-4 w-4 text-primary" />
              <Label className="text-xs font-semibold text-foreground">
                {t('scoping:justification.narrativeTitle')}
              </Label>
            </div>
            <p className="text-xs text-muted-foreground leading-relaxed">
              {liveNarrative}
            </p>
            <p className="text-xs text-muted-foreground/80 pt-1">
              * {t('scoping:justification.narrativeHint')}
            </p>
          </div>

          {/* Optional Supplementary Notes */}
          <div className="space-y-2">
            <Label htmlFor="supplementary-notes" className="text-xs font-semibold text-foreground">
              {t('scoping:justification.supplementaryNotesTitle')}
            </Label>
            <Textarea
              id="supplementary-notes"
              value={supplementaryNotes}
              onChange={(e) => !isLocked && setSupplementaryNotes(e.target.value)}
              disabled={isLocked}
              rows={3}
              placeholder={t('scoping:justification.supplementaryNotesPlaceholder')}
              className="text-xs rounded-md border-border bg-background focus:ring-primary"
            />
          </div>
        </div>

        <DialogFooter className="border-t border-border pt-4 flex flex-col-reverse sm:flex-row sm:items-center sm:justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={() => onOpenChange(false)}
            className="text-xs rounded-md w-full sm:w-auto min-h-[44px]"
          >
            {t('common:actions.cancel')}
          </Button>
          {!isLocked && (
            <Button
              type="button"
              size="sm"
              onClick={handleSave}
              className="text-xs rounded-md font-semibold w-full sm:w-auto min-h-[44px]"
            >
              <FileText className="h-3.5 w-3.5 mr-1.5" />
              {t('scoping:justification.saveButton')}
            </Button>
          )}
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
