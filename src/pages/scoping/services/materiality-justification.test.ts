import { describe, it, expect } from 'vitest';
import { generateMaterialityNarrative, isJustificationComplete } from './materiality-justification';

describe('materiality-justification service', () => {
  it('generates coherent Indonesian narrative when all 4 factors are provided', () => {
    const text = generateMaterialityNarrative({
      basis: 'Laba Sebelum Pajak (PBT)',
      omPercentage: 5,
      haircutPercentage: 25,
      entityCharacteristics: 'profit_oriented',
      internalControlMaturity: 'effective_strong',
      auditAdjustmentHistory: 'low_clean',
      systemStability: 'stable',
      language: 'id'
    });

    expect(text).toContain('Laba Sebelum Pajak');
    expect(text).toContain('5%');
    expect(text).toContain('25%');
    expect(text).toContain('PM 75%');
    expect(text).toContain('fokus pemangku kepentingan pada profitabilitas');
    expect(text).toContain('pengendalian internal yang dinilai efektif');
    expect(text).toContain('riwayat salah saji/koreksi audit');
    expect(text).toContain('stabilitas proses bisnis');
  });

  it('generates coherent English narrative when all 4 factors are provided', () => {
    const text = generateMaterialityNarrative({
      basis: 'Profit Before Tax',
      omPercentage: 5,
      haircutPercentage: 30,
      entityCharacteristics: 'asset_intensive',
      internalControlMaturity: 'moderate',
      auditAdjustmentHistory: 'moderate',
      systemStability: 'major_change_erp_restructure',
      language: 'en'
    });

    expect(text).toContain('Profit Before Tax');
    expect(text).toContain('capital-intensive nature');
    expect(text).toContain('PM 70% of OM');
    expect(text).toContain('moderate control environment');
    expect(text).toContain('major ERP rollout');
  });

  it('identifies incomplete and complete justifications accurately', () => {
    expect(isJustificationComplete(null)).toBe(false);
    expect(isJustificationComplete(undefined)).toBe(false);

    // Text-based justification
    expect(isJustificationComplete({
      justificationText: 'Penetapan OM 5% dan Haircut 25% sesuai baseline industri dan kestabilan sistem ERP.'
    })).toBe(true);

    expect(isJustificationComplete({
      justificationText: '   '
    })).toBe(false);

    expect(isJustificationComplete({
      entityCharacteristics: 'profit_oriented',
      internalControlMaturity: 'effective_strong',
      auditAdjustmentHistory: 'low_clean',
      systemStability: 'stable',
      autoGeneratedNarrative: 'Test narrative'
    })).toBe(true);

    // Missing one factor
    expect(isJustificationComplete({
      entityCharacteristics: 'profit_oriented',
      internalControlMaturity: 'effective_strong',
      auditAdjustmentHistory: 'low_clean',
      systemStability: undefined,
      autoGeneratedNarrative: 'Test narrative'
    } as unknown as Parameters<typeof isJustificationComplete>[0])).toBe(false);
  });
});
