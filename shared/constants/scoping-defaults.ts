/**
 * Normalizes an FSLI name for lookup.
 */
function normalizeFsli(name: string): string {
  return name.trim().toLowerCase();
}

const NORMALIZED_DEFAULTS = Object.fromEntries(
  Object.entries(FSLI_QUALITATIVE_DEFAULTS).map(([k, v]) => [normalizeFsli(k), v])
);

/**
 * Returns default qualitative ratings for an FSLI name.
 * Defaults all 8 pillars to 'Low' if not found.
 */
export function getQualitativeDefaults(fsliName: string): Record<number, string> {
  const normalized = normalizeFsli(fsliName);
  return NORMALIZED_DEFAULTS[normalized] || {
    1: "Low", 2: "Low", 3: "Low", 4: "Low", 
    5: "Low", 6: "Low", 7: "Low", 8: "Low"
  };
}
