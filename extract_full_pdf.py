import pdfplumber
import json
from datetime import datetime

pdf_path = "2024peraturan tk eselon i005.pdf"
output_path = "worker/knowledge-base.ts"

print("📖 Extracting PDF text...")

full_text = ""

with pdfplumber.open(pdf_path) as pdf:
    for i, page in enumerate(pdf.pages):
        text = page.extract_text()
        if text:
            full_text += text + "\n\n"

print(f"✅ Extracted {len(full_text):,} characters from {len(pdf.pages)} pages")

# Escape backticks and backslashes for TypeScript string
escaped_text = full_text.replace('\\', '\\\\').replace('`', '\\`')

# Generate TypeScript file
timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

ts_content = f'''/**
 * ICOFR Knowledge Base
 * 
 * Source: SK-5/DKU.MBU/11/2024 - Petunjuk Teknis Pengendalian Internal atas Pelaporan Keuangan
 * Extracted: {timestamp}
 * Pages: 119
 * Characters: {len(full_text):,}
 * 
 * DO NOT EDIT MANUALLY - Generated by extract_full_pdf.py
 * To regenerate: python extract_full_pdf.py
 */

export const ICOFR_KNOWLEDGE_BASE = `
DOKUMEN: SK-5/DKU.MBU/11/2024
JUDUL: Petunjuk Teknis Pengendalian Internal atas Pelaporan Keuangan (Internal Control Over Financial Reporting) Badan Usaha Milik Negara
DEPUTI: Deputi Bidang Keuangan dan Manajemen Risiko
KEMENTERIAN: Kementerian Badan Usaha Milik Negara Republik Indonesia
TANGGAL: 11 November 2024

================================================================================
{escaped_text}
`;

export const METADATA = {{
  documentNumber: "SK-5/DKU.MBU/11/2024",
  title: "Petunjuk Teknis Pengendalian Internal atas Pelaporan Keuangan (ICOFR) BUMN",
  date: "11 November 2024",
  pages: 119,
  characters: {len(full_text):,},
  extractedAt: "{timestamp}"
}};
'''

# Write to file
with open(output_path, 'w', encoding='utf-8') as f:
    f.write(ts_content)

print(f"💾 Saved to {output_path}")
print(f"📊 Metadata:")
print(f"   - Document: SK-5/DKU.MBU/11/2024")
print(f"   - Pages: 119")
print(f"   - Characters: {len(full_text):,}")
print(f"   - Extracted: {timestamp}")
